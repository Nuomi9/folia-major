import WebSocket from 'ws';
const list = await (await fetch('http://127.0.0.1:10099/json/list')).json();
const page = list.find(t => t.type === 'page');
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id=0; const p=new Map();
ws.on('message', r=>{const m=JSON.parse(r.toString()); if(m.id&&p.has(m.id)){p.get(m.id)(m);p.delete(m.id);}});
const send=(me,pa)=>new Promise(res=>{const n=++id;p.set(n,res);ws.send(JSON.stringify({id:n,method:me,params:pa}));});
await new Promise(r=>ws.on('open',r));
const ev=async e=>{const r=await send('Runtime.evaluate',{expression:e,awaitPromise:true,returnByValue:true});return r.result?.result?.value ?? 'EXC';};
console.log('playbackEntryView:', await ev(`localStorage.getItem('playback_entry_view') || localStorage.getItem('folia_playback_entry_view') || 'unset'`));
console.log('all entry keys:', await ev(`JSON.stringify(Object.keys(localStorage).filter(k=>/entry|view|lattice_open|queue_collage/i.test(k)).map(k=>k+'='+String(localStorage.getItem(k)).slice(0,30)))`));
console.log('lattice open flag:', await ev(`JSON.stringify(Object.keys(sessionStorage).map(k=>k+'='+String(sessionStorage.getItem(k)).slice(0,40)))`));
ws.close();
